def main():
    if not SOURCES_FILE.exists():
        print(f"Error: {SOURCES_FILE} not found!")
        return

    with open(SOURCES_FILE, "r", encoding="utf-8") as f:
        sources = json.load(f)

    updated_count = 0
    for entry in sources:
        eid = entry.get("id")
        if eid in metadata_updates:
            updates = metadata_updates[eid]
            entry["org"] = updates["org"]
            entry["title"] = updates["title"]
            entry["desc"] = updates["desc"]
            entry["tags"] = updates["tags"]
            updated_count += 1
            print(f"Updated metadata for id: {eid}")

    with open(SOURCES_FILE, "w", encoding="utf-8") as f:
        json.dump(sources, f, ensure_ascii=False, indent=2)
        f.write("\n")

    print(f"\nSuccessfully updated {updated_count} entries in {SOURCES_FILE.name}")

if __name__ == "__main__":
    main()
